#!/usr/bin/env bun
/**
 * Regenerates src/linguist-colors.ts: one color per file extension, taken from GitHub Linguist's
 * languages.yml (the colors of GitHub's language bar).
 *
 *   bun run linguist-colors
 *
 * Several languages can claim an extension. The winner is, in this order: the language from
 * PREFERRED, the language whose first (primary) extension it is, a language on Linguist's popular
 * list, a programming language before markup, data and prose, and then the name.
 */
import { join } from "node:path";

const REPO = "github-linguist/linguist";

/**
 * Ambiguous extensions where the rules above would pick a rarely meant language. Also applies when
 * Linguist only knows the language by file name (`go.mod`).
 */
const PREFERRED: Record<string, string> = {
  cfg: "INI",
  cls: "Apex",
  erb: "HTML+ERB",
  f: "Fortran",
  for: "Fortran",
  fs: "F#",
  h: "C",
  inc: "PHP",
  m: "Objective-C",
  md: "Markdown",
  mod: "Go Module",
  pl: "Perl",
  sql: "SQL",
  t: "Perl",
  v: "Verilog",
  yaml: "YAML",
};

/** Too ambiguous for any one color, or the usual language has none (`.txt`: Text, `.pro`: QMake). */
const SKIPPED = new Set(["in", "pro", "txt"]);

const TYPE_ORDER = ["programming", "markup", "data", "prose"];

interface Language {
  type: string;
  color?: string;
  extensions?: string[];
}

async function get(url: string): Promise<string> {
  const response = await fetch(url, { headers: { "User-Agent": "language-history" } });
  if (!response.ok) {
    throw new Error(`${url}: ${response.status}`);
  }
  return response.text();
}

const { sha } = JSON.parse(await get(`https://api.github.com/repos/${REPO}/commits/main`));
const raw = (path: string) => get(`https://raw.githubusercontent.com/${REPO}/${sha}/${path}`);
const languages: Record<string, Language> = Bun.YAML.parse(
  await raw("lib/linguist/languages.yml"),
) as Record<string, Language>;
const popular = new Set(Bun.YAML.parse(await raw("lib/linguist/popular.yml")) as string[]);

interface Candidate {
  name: string;
  color: string;
  primary: boolean;
}

const byExt = new Map<string, Candidate[]>();
for (const [name, language] of Object.entries(languages)) {
  if (!language.color) {
    continue;
  }
  (language.extensions ?? []).forEach((extension, i) => {
    // Linguist lists compound extensions (".d.ts", ".blade.php"); the tool only sees the last part.
    const ext = extension.slice(extension.lastIndexOf(".") + 1).toLowerCase();
    const list = byExt.get(ext) ?? [];
    list.push({ name, color: language.color as string, primary: i === 0 });
    byExt.set(ext, list);
  });
}

const rank = (ext: string, c: Candidate) => [
  PREFERRED[ext] === c.name ? 0 : 1,
  c.primary ? 0 : 1,
  popular.has(c.name) ? 0 : 1,
  TYPE_ORDER.indexOf(languages[c.name].type),
];

for (const [ext, name] of Object.entries(PREFERRED)) {
  const color = languages[name]?.color;
  if (!color) {
    throw new Error(`PREFERRED: ${name} (for .${ext}) has no color in Linguist`);
  }
  const list = byExt.get(ext) ?? [];
  if (!list.some((c) => c.name === name)) {
    byExt.set(ext, [...list, { name, color, primary: false }]);
  }
}
for (const ext of SKIPPED) {
  byExt.delete(ext);
}

const colors: [string, string, string][] = [];
for (const [ext, candidates] of [...byExt].sort(([a], [b]) => (a < b ? -1 : 1))) {
  const [winner, ...others] = candidates.sort((a, b) => {
    const ra = rank(ext, a);
    const rb = rank(ext, b);
    const i = ra.findIndex((v, j) => v !== rb[j]);
    return i >= 0 ? ra[i] - rb[i] : a.name.localeCompare(b.name);
  });
  colors.push([ext, winner.color.toLowerCase(), winner.name]);
  if (others.length && process.argv.includes("--verbose")) {
    console.log(`.${ext}: ${winner.name} over ${others.map((c) => c.name).join(", ")}`);
  }
}

const out = join(import.meta.dir, "../src/linguist-colors.ts");
await Bun.write(
  out,
  `// Generated by scripts/linguist-colors.ts from github-linguist/linguist@${sha.slice(0, 12)}
// (lib/linguist/languages.yml). Do not edit; run \`bun run linguist-colors\`.
//
// Linguist: Copyright (c) 2017 GitHub, Inc. Released under the MIT license:
// https://github.com/github-linguist/linguist/blob/main/LICENSE

/** GitHub's language color per file extension (lower-case, without the dot). */
export const LINGUIST_COLORS: Record<string, string> = {
${colors.map(([ext, color, name]) => `  ${JSON.stringify(ext)}: "${color}", // ${name}`).join("\n")}
};
`,
);
const format = Bun.spawn(["bunx", "biome", "format", "--write", out], { stdout: "ignore" });
if ((await format.exited) !== 0) {
  throw new Error(`biome format ${out} failed`);
}
console.log(`Wrote ${colors.length} extensions to ${out}`);
